def item(iid, group, text, typ='binary', when='all', photo=False, fields=0, unit='', labels='',
         norms=None, since=OLD, aliases='', notes='', hint='', opts=None):
    """norms — список до 3 кортежів (norm_min, norm_max, warn_min, warn_max); None = без норми."""
    row = {c: '' for c in COLS}
    row.update({
        'item_id': 'mech.' + iid, 'role': 'Механік',
        'group_id': group, 'group_title': GTITLE[group], 'group_seq': GSEQ[group],
        'seq': sum(1 for r in items if r['group_id'] == group) + 1,
        'text': text, 'type': typ, 'fields': fields, 'unit': unit, 'labels': labels,
        'visible_on': when, 'photo_required': bool(photo),
        'active_from': since, 'active_to': '', 'text_aliases': aliases, 'notes': notes, 'hint': hint,
    })
    for f, n in enumerate(norms or [], 1):
        if n is None:
            continue
        row['norm_min_%d' % f], row['norm_max_%d' % f], row['warn_min_%d' % f], row['warn_max_%d' % f] = n
    items.append(row)
    for o in (opts or []):
        value, status = o[0], o[1]
        req = o[2] if len(o) > 2 else ''
        options.append(('mech.' + iid, value, status, req))


